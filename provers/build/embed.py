"""Write provers/<name>.wasm.js for each provers/<name>.wasm.

Each file holds the program gzip-compressed and base64-encoded, and registers it with LogicUSProvers. The page loads
it with a <script> tag, which browsers allow also when LogicUS is opened as a local file (they block fetching a .wasm
file from file:// pages). CI runs it with --check.

Usage: python3 provers/build/embed.py           write the scripts
       python3 provers/build/embed.py --check   check that each script holds its .wasm file
"""
import base64
import gzip
import pathlib
import re
import sys

PROVERS = pathlib.Path(__file__).resolve().parent.parent
NAMES = {"prover9": "Prover9", "mace4": "Mace4", "prooftrans": "prooftrans (LADR)", "interpformat": "interpformat (LADR)",
         "ladr_to_tptp": "ladr_to_tptp (LADR)", "tptp_to_ladr": "tptp_to_ladr (LADR)", "eprover": "E"}

if sys.argv[1:] == ["--check"]:
    for name in NAMES:
        script = (PROVERS / f"{name}.wasm.js").read_text()
        data = re.search(r'register\("[a-z0-9_]+", "([A-Za-z0-9+/=]+)"\)', script).group(1)
        if gzip.decompress(base64.b64decode(data)) != (PROVERS / f"{name}.wasm").read_bytes():
            sys.exit(f"{name}.wasm.js does not match {name}.wasm: run provers/build/embed.py")
    print("ok")
    sys.exit(0)

for name, title in NAMES.items():
    wasm = (PROVERS / f"{name}.wasm").read_bytes()
    data = base64.b64encode(gzip.compress(wasm, compresslevel=9, mtime=0)).decode("ascii")
    (PROVERS / f"{name}.wasm.js").write_text(
        f"// {title} compiled to WebAssembly ({name}.wasm), gzip-compressed and base64-encoded.\n"
        "// Generated by provers/build/embed.py: do not edit.\n"
        f'LogicUSProvers.register("{name}", "{data}");\n'
    )
    print(f"{name}.wasm.js: {len(data)} bytes")
