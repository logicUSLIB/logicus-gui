"""Write examples/examples.js from examples/index.json and the schemas it lists.

The EXAMPLES panel reads the examples from that script instead of fetching the JSON files, so it also works when
LogicUS is opened as a local file. Run it after adding or changing an example:

    python3 scripts/build-examples.py
"""
import json
import pathlib

EXAMPLES = pathlib.Path(__file__).resolve().parent.parent / "examples"

index = json.loads((EXAMPLES / "index.json").read_text(encoding="utf-8"))
for example in index:
    example["schema"] = json.loads((EXAMPLES / example["file"]).read_text(encoding="utf-8"))
(EXAMPLES / "examples.js").write_text(
    "// The examples of examples/index.json with their schemas. Generated by scripts/build-examples.py: do not edit.\n"
    "const LOGICUS_EXAMPLES = " + json.dumps(index, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(f"examples.js: {len(index)} examples")
